void aes_test_encrypt(unsigned nbytes) {
    cipher_context_t ctx;
    uint8_t output_data[nbytes];

    aes_init(&ctx, key, sizeof(key));
    for (unsigned i = 0; i < nbytes; i+= AES_BLOCK_SIZE) {
        aes_encrypt(&ctx, &input_data[i], &output_data[i]);
    }
}

void aes_test_decrypt(unsigned nbytes) {
    cipher_context_t ctx;
    uint8_t output_data[nbytes];

    aes_init(&ctx, key, sizeof(key));

    for (unsigned i = 0; i < nbytes; i+= AES_BLOCK_SIZE) {
        aes_decrypt(&ctx, &input_data[i], &output_data[i]);
    }
}

